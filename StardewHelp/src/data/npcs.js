/**
 * Obtiene los NPCs que cumplen años en el día y estación actuales
 */
export function getBirthdays(season, day) {
  return npcs.filter(n => n.birthday.season === season && n.birthday.day === day);
}

/**
 * Obtiene los cumpleaños próximos (los siguientes N días)
 */
export function getUpcomingBirthdays(season, day, daysAhead = 7) {
  const upcoming = [];
  for (let i = 1; i <= daysAhead; i++) {
    const checkDay = day + i;
    if (checkDay <= 28) {
      const birthdays = npcs.filter(n => n.birthday.season === season && n.birthday.day === checkDay);
      birthdays.forEach(npc => upcoming.push({ npc, daysUntil: i, day: checkDay }));
    }
  }
  return upcoming;
}
