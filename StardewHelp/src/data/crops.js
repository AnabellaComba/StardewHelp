/**
 * Determina si un cultivo puede plantarse hoy y cosechar antes del fin de estación.
 * @param {object} crop - Objeto cultivo
 * @param {string} season - Estación actual ('primavera','verano','otoño','invierno')
 * @param {number} day - Día actual (1-28)
 * @returns {boolean}
 */
export function canPlantToday(crop, season, day) {
  if (!crop.seasons.includes(season)) return false;

  // Para cultivos multi-estación, verificar si la estación actual es válida
  if (crop.multiSeason) {
    const seasonIndex = ['primavera', 'verano', 'otoño', 'invierno'].indexOf(season);
    const cropSeasonIndices = crop.seasons.map(s =>
      ['primavera', 'verano', 'otoño', 'invierno'].indexOf(s)
    );
    // Verificar que la siguiente estación también sea válida para el cultivo
    const nextSeasonIndex = (seasonIndex + 1) % 4;
    const continuesNextSeason = cropSeasonIndices.includes(nextSeasonIndex);
    if (continuesNextSeason) return true; // Puede plantarse en cualquier día válido de su estación
  }

  // Días restantes en la estación (incluyendo el día actual)
  const daysLeft = 28 - day + 1;
  // Necesita daysToGrow noches + al menos 1 día para cosechar
  // El cultivo se planta hoy, necesita daysToGrow noches para madurar
  // Si se planta el día D, estará listo el día D + daysToGrow
  // Debe estar listo en o antes del día 28: D + daysToGrow <= 28
  return day + crop.daysToGrow <= 28;
}

/**
 * Devuelve los cultivos disponibles para plantar en el día y estación actuales
 */
export function getCropsForDay(season, day) {
  return crops.filter(crop => canPlantToday(crop, season, day));
}

/**
 * Devuelve los cultivos de la estación pero que YA NO se pueden plantar
 */
export function getTooLateCrops(season, day) {
  return crops.filter(crop => {
    if (!crop.seasons.includes(season)) return false;
    return !canPlantToday(crop, season, day);
  });
}
