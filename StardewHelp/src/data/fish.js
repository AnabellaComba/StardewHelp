/**
 * Filtra peces disponibles según estación, día, clima y hora
 * @param {string} season - estación actual
 * @param {string} weather - 'sol' | 'lluvia' | 'cualquiera'
 * @returns {Array} peces disponibles
 */
export function getFishForSeason(season, weather = 'cualquiera') {
  return fish.filter(f => {
    if (!f.seasons.includes(season)) return false;
    if (f.weather !== 'cualquiera' && weather !== 'cualquiera') {
      if (f.weather !== weather) return false;
    }
    return true;
  });
}
